#!/usr/bin/env python3
"""Read project-specific fields from an external flash image file.

Workflow:
1. Put exactly one flash image file into the local "input" folder.
2. Run this script with Python.
3. Read the generated "device_material_info.txt" file.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path


FBCT_BASE = 0x2000
FBCT_USED_LENGTH = 0x1A2
SELECTOR_2_OFFSET = 0x2006
SELECTOR_2_LENGTH = 0x100
SELECTOR_3_OFFSET = 0x2106
SELECTOR_3_LENGTH = 0x10
FACTORY_SELECTOR_6_OFFSET = 0x2116
FACTORY_SELECTOR_6_LENGTH = 0x0A

SAV_OFFSET = 0x3000
SAV_LENGTH = 0x288
SELECTOR_4_OFFSET = 0x306C
SELECTOR_4_LENGTH = 0x10
SELECTOR_5_OFFSET = 0x307C
SELECTOR_5_LENGTH = 0x01
SELECTOR_6_OFFSET = 0x307D
SELECTOR_6_LENGTH = 0x0A

FBCT_MAGIC = bytes.fromhex("46 42 43 54")
SAV_MAGIC = bytes.fromhex("18 53 41 56")

SCRIPT_DIR = Path(__file__).resolve().parent
INPUT_DIR = SCRIPT_DIR / "input"
OUTPUT_FILE = SCRIPT_DIR / "device_material_info.txt"
DEVICE_MATERIAL_FILE = SCRIPT_DIR / "pp_device_material.generated.h"
PLACEHOLDER_INPUT_FILES = {"README.md", ".gitkeep"}


def to_hex(data: bytes) -> str:
    return data.hex()


def to_spaced_hex(data: bytes) -> str:
    return " ".join(f"{byte:02x}" for byte in data)


def to_c_initializer(data: bytes, indent: str = "  ", per_line: int = 12) -> str:
    parts = [f"0x{byte:02x}" for byte in data]
    lines = []
    for start in range(0, len(parts), per_line):
        chunk = ", ".join(parts[start:start + per_line])
        if start + per_line < len(parts):
            chunk += ","
        lines.append(indent + chunk + " \\")
    return "\n".join(lines)


def read_slice(blob: bytes, offset: int, length: int) -> bytes:
    end = offset + length
    if end > len(blob):
        raise ValueError(
            f"Image is too small for offset 0x{offset:04x} length 0x{length:x}. "
            f"Need at least 0x{end:x} bytes, found 0x{len(blob):x} bytes."
        )
    return blob[offset:end]


def build_device_material_header(selector_2: bytes,
                                 selector_3: bytes,
                                 selector_6: bytes,
                                 source_path: Path,
                                 sha256: str) -> str:
    return "\n".join(
        [
            "#pragma once",
            "",
            "#include <stdint.h>",
            "",
            "// Generated by tools/flash_image_reader/read_flash_data.py.",
            f"// Source file: {source_path.name}",
            f"// Source SHA-256: {sha256}",
            "//",
            "// Fill PP_DEVICE_PUBLIC_ADDR_LE_BYTES with your device's public BLE",
            "// address in little-endian byte order. You can get the address from",
            "// a normal Bluetooth scanner app or your phone's Bluetooth device info.",
            "// Example: address AA:BB:CC:DD:EE:FF becomes { 0xff, 0xee, 0xdd, 0xcc, 0xbb, 0xaa }.",
            "",
            "#define PP_DEVICE_MATERIAL_CONFIGURED 0",
            "",
            "#define PP_DEVICE_PUBLIC_ADDR_LE_BYTES \\",
            "  { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 }",
            "",
            "#define PP_DEVICE_CERT_BLOCK_BYTES \\",
            "  { \\",
            f"{to_c_initializer(selector_2, indent='    ')}",
            "  }",
            "",
            "#define PP_DEVICE_SELECTOR3_BYTES \\",
            "  { \\",
            f"{to_c_initializer(selector_3, indent='    ')}",
            "  }",
            "",
            "// This selector is still modeled from the current protocol path, not",
            "// read from the external flash report.",
            "#define PP_DEVICE_AUTH_SELECTOR4_BYTES \\",
            "  { 0x85, 0x6a, 0x07, 0x37, 0xb1, 0x30, 0x47, 0x6e, 0x6c, 0x82, 0xf1, 0x00, 0xd3, 0x06, 0x7a, 0xe1 }",
            "",
            "#define PP_DEVICE_SELECTOR6_BYTES \\",
            "  { \\",
            f"{to_c_initializer(selector_6, indent='    ')}",
            "  }",
            "",
            "extern const uint8_t REAL_PLUSPLUS_ADDR_LE[6];",
            "extern const uint8_t PLUSPLUS_FACTORY_CERT_BLOCK[256];",
            "extern const uint8_t PLUSPLUS_FACTORY_SELECTOR3[16];",
            "extern const uint8_t PLUSPLUS_FACTORY_SELECTOR4[16];",
            "extern const uint8_t PLUSPLUS_FACTORY_SELECTOR6[10];",
            "",
        ]
    )


def find_input_file() -> Path:
    INPUT_DIR.mkdir(exist_ok=True)
    files = [
        path
        for path in INPUT_DIR.iterdir()
        if path.is_file() and not path.name.startswith(".") and path.name not in PLACEHOLDER_INPUT_FILES
    ]
    if not files:
        raise FileNotFoundError(
            "No input file found.\n"
            f"Put one flash image file into:\n{INPUT_DIR}"
        )
    if len(files) > 1:
        file_list = "\n".join(f"- {path.name}" for path in sorted(files))
        raise FileExistsError(
            "More than one file was found in the input folder.\n"
            "Please leave exactly one flash image file there.\n"
            f"Found:\n{file_list}"
        )
    return files[0]


def build_report(source_path: Path, blob: bytes) -> str:
    fbct = read_slice(blob, FBCT_BASE, FBCT_USED_LENGTH)
    selector_2 = read_slice(blob, SELECTOR_2_OFFSET, SELECTOR_2_LENGTH)
    selector_3 = read_slice(blob, SELECTOR_3_OFFSET, SELECTOR_3_LENGTH)
    factory_selector_6 = read_slice(blob, FACTORY_SELECTOR_6_OFFSET, FACTORY_SELECTOR_6_LENGTH)
    sav = read_slice(blob, SAV_OFFSET, SAV_LENGTH)
    selector_4 = read_slice(blob, SELECTOR_4_OFFSET, SELECTOR_4_LENGTH)
    selector_5 = read_slice(blob, SELECTOR_5_OFFSET, SELECTOR_5_LENGTH)
    selector_6 = read_slice(blob, SELECTOR_6_OFFSET, SELECTOR_6_LENGTH)

    fbct_magic_ok = fbct[:4] == FBCT_MAGIC
    sav_magic_ok = sav[:4] == SAV_MAGIC

    sha256 = hashlib.sha256(blob).hexdigest()

    return "\n".join(
        [
            "Pokemon GO Plus + Device Material Report",
            "===========================================",
            "",
            f"Source file: {source_path.name}",
            f"Source path: {source_path}",
            f"File size: {len(blob)} bytes (0x{len(blob):x})",
            f"SHA-256: {sha256}",
            "",
            "Quick checks",
            "------------",
            f"FBCT magic at 0x2000: {'OK' if fbct_magic_ok else 'MISMATCH'}",
            f"FBCT bytes: {to_spaced_hex(fbct[:4])}",
            f".SAV magic at 0x3000: {'OK' if sav_magic_ok else 'MISMATCH'}",
            f".SAV bytes: {to_spaced_hex(sav[:4])}",
            "",
            "Required donor data",
            "-------------------",
            "donor_public_ble_address = NOT PRESENT IN EXTERNAL FLASH IMAGE",
            f"selector_2_cert_block_offset = 0x{SELECTOR_2_OFFSET:04x}",
            f"selector_2_cert_block_length = 0x{SELECTOR_2_LENGTH:x}",
            f"selector_2_cert_block_hex = {to_hex(selector_2)}",
            f"selector_3_key_lane_offset = 0x{SELECTOR_3_OFFSET:04x}",
            f"selector_3_key_lane_length = 0x{SELECTOR_3_LENGTH:x}",
            f"selector_3_key_lane_hex = {to_hex(selector_3)}",
            f"factory_selector_6_offset = 0x{FACTORY_SELECTOR_6_OFFSET:04x}",
            f"factory_selector_6_length = 0x{FACTORY_SELECTOR_6_LENGTH:x}",
            f"factory_selector_6_hex = {to_hex(factory_selector_6)}",
            "",
            "Recommended donor data",
            "----------------------",
            f"full_sav_image_offset = 0x{SAV_OFFSET:04x}",
            f"full_sav_image_length = 0x{SAV_LENGTH:x}",
            f"full_sav_image_hex = {to_hex(sav)}",
            f"persisted_selector_4_offset = 0x{SELECTOR_4_OFFSET:04x}",
            f"persisted_selector_4_length = 0x{SELECTOR_4_LENGTH:x}",
            f"persisted_selector_4_hex = {to_hex(selector_4)}",
            f"persisted_selector_5_offset = 0x{SELECTOR_5_OFFSET:04x}",
            f"persisted_selector_5_length = 0x{SELECTOR_5_LENGTH:x}",
            f"persisted_selector_5_hex = {to_hex(selector_5)}",
            f"persisted_selector_6_offset = 0x{SELECTOR_6_OFFSET:04x}",
            f"persisted_selector_6_length = 0x{SELECTOR_6_LENGTH:x}",
            f"persisted_selector_6_hex = {to_hex(selector_6)}",
            "",
            "Full FBCT used region",
            "---------------------",
            f"fbct_used_region_offset = 0x{FBCT_BASE:04x}",
            f"fbct_used_region_length = 0x{FBCT_USED_LENGTH:x}",
            f"fbct_used_region_hex = {to_hex(fbct)}",
            "",
            "Notes",
            "-----",
            "This file contains the external-flash fields from the project cheat sheet.",
            "You still need the donor public BLE address from a separate source.",
            f"Generated firmware material header: {DEVICE_MATERIAL_FILE}",
        ]
    )


def main() -> int:
    try:
        source_path = find_input_file()
        blob = source_path.read_bytes()
        report = build_report(source_path, blob)
        selector_2 = read_slice(blob, SELECTOR_2_OFFSET, SELECTOR_2_LENGTH)
        selector_3 = read_slice(blob, SELECTOR_3_OFFSET, SELECTOR_3_LENGTH)
        factory_selector_6 = read_slice(blob, FACTORY_SELECTOR_6_OFFSET, FACTORY_SELECTOR_6_LENGTH)
        material = build_device_material_header(
            selector_2,
            selector_3,
            factory_selector_6,
            source_path,
            hashlib.sha256(blob).hexdigest(),
        )
        OUTPUT_FILE.write_text(report, encoding="utf-8", newline="\n")
        DEVICE_MATERIAL_FILE.write_text(material, encoding="utf-8", newline="\n")
    except Exception as exc:
        print()
        print("Read failed.")
        print(exc)
        print()
        return 1

    print()
    print("Read complete.")
    print(f"Input file:  {source_path.name}")
    print(f"Output file: {OUTPUT_FILE}")
    print(f"Header file: {DEVICE_MATERIAL_FILE}")
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
